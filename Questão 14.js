// Função que calcula a soma de dois números
function somar(n1, n2) {
    return n1 + n2; // Retorna a soma dos dois números
}

// Definindo dois números
let numero1 = 10; // Primeiro número
let numero2 = 5;  // Segundo número

// Chamando a função e armazenando o resultado
let resultado = somar(numero1, numero2);

// Exibindo o resultado no console
console.log(`A soma de ${numero1} e ${numero2} é: ${resultado}`);
